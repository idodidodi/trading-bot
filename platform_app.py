def load_env():
    path = Path(os.environ.get('TRADING_BOT_ENV_FILE', str(ROOT / '.env'))).expanduser()
    if path.exists():
        for line in path.read_text(encoding='utf-8').splitlines():
            if line.strip() and not line.lstrip().startswith('#'):
                # Ignore notes/headings pasted alongside credentials. Never log
                # arbitrary .env text: even a malformed line can contain a key.
                if '=' not in line:
                    continue
                key, value = line.split('=', 1)
                key = key.strip().removeprefix('export ').strip()
                # Source production must be selected by the launching process,
                # never inherited accidentally from a shared credentials file.
                if key == 'TRADING_BOT_ENV':
                    continue
                if not re.fullmatch(r'[A-Za-z_][A-Za-z0-9_]*', key):
                    continue
                value = value.strip()
                if len(value) >= 2 and value[0] == value[-1] and value[0] in ('"', "'"):
                    value = value[1:-1]
                os.environ.setdefault(key, value)


def load_rules():
    text = SKILL.read_text(encoding='utf-8')
    patterns = {
        'rsi_period': r'- RSI: (\d+) periods, Wilder smoothing, close prices\.',
        'rsi_tolerance': r'- RSI tolerance: ([\d.]+) points, inclusive, in both directions\.',
        'bb_period': r'- Bollinger Bands: (\d+)-period',
        'bb_multiplier': r'plus/minus ([\d.]+) population standard deviations',
        'pivot_left': r'- Pivot confirmation: (\d+) candles to the left',
        'pivot_right': r'candles to the left and (\d+) to the right',
        'min_spacing': r'- Pivot spacing: (\d+)–\d+ candles',
        'max_spacing': r'- Pivot spacing: \d+–(\d+) candles',
    }
    rules = {}
    for key, pattern in patterns.items():
        match = re.search(pattern, text)
        if not match:
            raise ValueError(f'Cannot read {key} from {SKILL}; update the parser explicitly.')
        rules[key] = float(match[1]) if key in ('bb_multiplier', 'rsi_tolerance') else int(match[1])
    if any(v <= 0 for v in rules.values()) or rules['min_spacing'] > rules['max_spacing']:
        raise ValueError('Invalid indicator or pivot settings in skill.')
    source = re.search(r'- Divergence price source: (close)\.', text)
    if not source:
        raise ValueError('Missing close-based divergence price source in skill.')
    rules['price_source'] = source[1]
    rules['skill_hash'] = hashlib.sha256(text.encode()).hexdigest()[:16]
    return rules


def rsi_divergence_matches(first, second, direction, tolerance=0):
    improvement = second - first if direction == 'bullish' else first - second
    return improvement > 0 or (tolerance > 0 and improvement >= -tolerance)


def validate_signal(body, rules):
    """Recheck the evidence generated by the local engine or legacy webhook."""
    if body.get('rules') != rules:
        raise ValueError('Rules differ; restart the scanner with the current Markdown settings.')
    for key in ('symbol', 'timeframe'):
        pattern = r'[A-Za-z0-9_^=:./!\-]{1,100}' if key == 'symbol' else r'[A-Za-z0-9_:./!\-]{1,100}'
        if not isinstance(body.get(key), str) or not re.fullmatch(pattern, body[key]):
            raise ValueError(f'Invalid {key}')
    if body.get('direction') not in ('bullish', 'bearish'):
        raise ValueError('Invalid direction')
    keys = ('price1', 'price2', 'rsi1', 'rsi2', 'band1', 'band2')
    for key in keys:
        v = body.get(key)
        if isinstance(v, bool) or not isinstance(v, (int, float)) or not math.isfinite(v):
            raise ValueError(f'Invalid {key}')
    for key in ('pivot1', 'pivot2', 'confirmed_at', 'spacing'):
        if type(body.get(key)) is not int or body[key] <= 0:
            raise ValueError(f'Invalid {key}')
    if not body['pivot1'] < body['pivot2'] < body['confirmed_at']:
        raise ValueError('Invalid pivot/confirmation ordering')
    if body['confirmed_at'] > int(time.time() * 1000) + 60_000:
        raise ValueError('Confirmation is in the future')
    if not all(0 <= body[k] <= 100 for k in ('rsi1', 'rsi2')):
        raise ValueError('RSI outside 0–100')
    if not rules['min_spacing'] <= body['spacing'] <= rules['max_spacing']:
        raise ValueError('Pivot spacing outside range')
    touch = body.get('band_touch_price', body['price2'])
    if isinstance(touch, bool) or not isinstance(touch, (int, float)) or not math.isfinite(touch):
        raise ValueError('Invalid band touch price')
    if (body['direction'] == 'bullish' and touch > body['price2']) or (body['direction'] == 'bearish' and touch < body['price2']):
        raise ValueError('Band touch inconsistent with pivot price')
    if body['direction'] == 'bullish':
        valid = body['price2'] < body['price1'] and rsi_divergence_matches(body['rsi1'], body['rsi2'], 'bullish', rules.get('rsi_tolerance', 0)) and touch <= body['band2']
    else:
        valid = body['price2'] > body['price1'] and rsi_divergence_matches(body['rsi1'], body['rsi2'], 'bearish', rules.get('rsi_tolerance', 0)) and touch >= body['band2']
    if not valid:
        raise ValueError('Divergence or band-touch rule failed')
    # Store only known fields; never persist the webhook authentication secret.
    clean = {k: body[k] for k in ('symbol', 'timeframe', 'direction', *keys, 'pivot1', 'pivot2', 'confirmed_at', 'spacing', 'rules')}
    if 'band_touch_price' in body:
        clean['band_touch_price'] = touch
    if any(k in body for k in ('signal_status', 'alert_timing', 'pivot_closed_at')):
        if (body.get('signal_status') != 'provisional' or body.get('alert_timing') != 'pivot_close'
                or type(body.get('pivot_closed_at')) is not int or body['pivot_closed_at'] != body['confirmed_at']):
            raise ValueError('Invalid provisional signal timing')
        clean.update(signal_status='provisional', alert_timing='pivot_close', pivot_closed_at=body['pivot_closed_at'])
    for key, start in (('pivot1_closed_at', 'pivot1'), ('pivot2_closed_at', 'pivot2')):
        if key in body:
            if type(body[key]) is not int or not body[start] < body[key] <= body['confirmed_at']:
                raise ValueError(f'Invalid {key}')
            clean[key] = body[key]
    if 'pivot1_closed_at' in clean and clean['pivot1_closed_at'] > body['pivot2']:
        raise ValueError('Overlapping pivot candles')
    if clean.get('signal_status') == 'provisional' and clean.get('pivot2_closed_at', body['confirmed_at']) != body['confirmed_at']:
        raise ValueError('Invalid signal candle close')
    return clean


class Store:
    def __init__(self, path=None):
        # Legacy path arguments are ignored; never create or open a local DB.
        self.path = None
        self.guard = None
        with self.connect() as db:
            version = db.execute('SELECT version FROM schema_version WHERE id=1').fetchone()
            if version != (2,):
                raise RuntimeError('Apply the prepared Postgres schema before starting')

    def connect(self):
        from postgres_store import connect
        if self.guard is not None:
            self.guard.check()
        return connect()

    def acquire_worker(self):
        from postgres_store import WorkerGuard
        if self.guard is None:
            with self.connect() as db:
                if db.execute('SELECT enabled FROM runtime_control WHERE id=1').fetchone() != (True,):
                    raise RuntimeError('Runtime activation is disabled; complete the manual migration first')
            self.guard = WorkerGuard()
        return self.guard

    def insert(self, payload, delivery_status='pending',catchup_id=None):
        # Structural confirmations remain findings, without a second Telegram alert.
        if delivery_status == 'pending' and payload.get('signal_status') != 'provisional':
            delivery_status = 'cancelled'
        identity = [payload[k] for k in ('symbol', 'timeframe', 'direction', 'pivot1', 'pivot2')]
        if payload.get('signal_status') == 'provisional': identity.append('warmup')
        if payload.get('review_slot'): identity.append(payload['review_slot'])
        key = hashlib.sha256(json.dumps(identity).encode()).hexdigest()
        with self.connect() as db:
            result = db.execute('INSERT INTO signals(id,payload,received,status) VALUES(%s,%s,%s,%s) ON CONFLICT DO NOTHING',
                                (key, json.dumps(payload), time.time(),delivery_status))
            if result.rowcount==1 and catchup_id:
                db.require_table('catchup_findings')
                db.execute('INSERT INTO catchup_findings VALUES(%s,%s) ON CONFLICT DO NOTHING',(catchup_id,key))
            inserted = result.rowcount == 1
            if inserted:
                from postgres_store import remember_finding
                remember_finding(db, 'live', payload)
            if inserted:
                from telegram_routing import remember
                remember(db, signal_alert_event(payload), payload.get('market'), 'rsi')
            return inserted

    def log(self, event, details):
        from runtime_env import environment
        if environment() != 'prod':
            stamp = datetime.now(ZoneInfo('Asia/Jerusalem')).strftime('%Y-%m-%d %H:%M:%S %z')
            print(f'[DEV {stamp}] {event}: {details}', flush=True)
            return
        verbose_default = 'true' if os.environ.get('TRADING_BOT_LOG_FILE') else 'false'
        if os.environ.get('TRADING_BOT_VERBOSE_LOGS', verbose_default).lower() in ('true', '1'):
            stamp = datetime.now(ZoneInfo('Asia/Jerusalem')).strftime('%Y-%m-%d %H:%M:%S %z')
            print(f'[PROD {stamp}] {event}: {details}', flush=True)
        try:
            with self.connect() as db:
                db.require_table('activity_log')
                db.execute('INSERT INTO activity_log(occurred,event,details) VALUES(%s,%s,%s)', (time.time(), event, details))
        except Exception as exc:
            # Failure reporting must not kill a worker when SQLite is busy.
            print(f'{event}: {details} (activity database unavailable)', file=sys.stderr, flush=True)

    def rows(self):
        with self.connect() as db:
            return db.execute('SELECT payload,status,attempts,error FROM signals ORDER BY received DESC LIMIT 100').fetchall()


def signal_alert_identity(payload):
    """Telegram groups reference pivots; dashboard findings keep their pair IDs."""
    return [payload[k] for k in ('symbol', 'timeframe', 'direction', 'pivot2')] + [
        'provisional' if payload.get('signal_status') == 'provisional' else 'confirmed']


def signal_alert_event(payload):
    return 'divergence:' + hashlib.sha256(json.dumps(signal_alert_identity(payload)).encode()).hexdigest()


def signal_alert_delivered(store, payload):
    # Include pre-grouping deliveries so upgrading does not repeat an alert
    # when another reference pivot for an already delivered candle arrives.
    with store.connect() as db:
        return db.execute("SELECT 1 FROM signals\n            WHERE status IN ('sent','suppressed')\n            AND (payload::jsonb->>'symbol')=%s\n            AND (payload::jsonb->>'timeframe')=%s\n            AND (payload::jsonb->>'direction')=%s\n            AND (payload::jsonb->>'pivot2')::bigint=%s\n            AND CASE WHEN (payload::jsonb->>'signal_status')='provisional'\n                THEN 'provisional' ELSE 'confirmed' END=%s LIMIT 1",
            signal_alert_identity(payload)).fetchone() is not None


def message(payload):
    provisional = payload.get('signal_status') == 'provisional'
    def stamp(value):
        return datetime.fromtimestamp(value / 1000, ZoneInfo('Asia/Jerusalem')).strftime('%d %b %Y at %H:%M (Israel time)') if value else 'unavailable in saved finding'
    def candle_range(label, opened_at, closed_at):
        opened = datetime.fromtimestamp(opened_at / 1000, ZoneInfo('Asia/Jerusalem'))
        if closed_at:
            closed = datetime.fromtimestamp(closed_at / 1000, ZoneInfo('Asia/Jerusalem'))
            end = closed.strftime('%H:%M' if opened.date() == closed.date() else '%d.%m.%y %H:%M')
        else:
            end = 'unavailable in saved finding'
        return f"{label} candle {opened:%d.%m.%y} between {opened:%H:%M} to {end}"
    first_close = payload.get('pivot1_closed_at')
    second_close = payload.get('pivot2_closed_at', payload.get('pivot_closed_at'))
    timing = (candle_range('Reference', payload['pivot1'], first_close) + '\n'
              + candle_range('Signal', payload['pivot2'], second_close))
    if payload.get('detected_at'):
        timing += f"\nDetected: {stamp(payload['detected_at'])}"
    if not provisional:
        timing += f"\nConfirmed: {stamp(payload['confirmed_at'])}"
    return (f"{payload['direction'].upper()} RSI divergence{' · candle closed' if provisional else ' · structurally confirmed'}\n"
            f"{payload['symbol']} · {payload['timeframe']}\n"
            f"Price: {payload['price1']:g} → {payload['price2']:g}\n"
            f"RSI({payload['rules']['rsi_period']}): {payload['rsi1']:.2f} → {payload['rsi2']:.2f}\n"
            f"{'Lower' if payload['direction'] == 'bullish' else 'Upper'} BB touch: {payload['band2']:g}\n"
            f"{timing}")


def telegram_connection_error(exc):
    reason = exc.reason if isinstance(exc, urllib.error.URLError) else exc
    if isinstance(reason, ssl.SSLCertVerificationError):
        return ('Telegram TLS certificate verification failed. Check the CA certificates '
                'for this Python interpreter, or use the configured project interpreter. '
                'Do not disable TLS verification.')
    if isinstance(reason, TimeoutError):
        return 'Telegram connection timed out. Check Internet/proxy access.'
    return 'Telegram connection failed. Check Internet/proxy access.'


def quiet_hours(now=None):
    local=datetime.fromtimestamp(time.time() if now is None else now,ZoneInfo('Asia/Jerusalem'))
    minute=local.hour*60+local.minute
    return minute>=23*60+30 or minute<6*60+30


class TelegramDestinationError(RuntimeError):
    """Telegram definitively rejected the destination; safe to use General."""


def send_telegram(token, chat_id, text, silent=False, source_identity=None):
    from telegram_delivery import footer
    from telegram_formatting import presentation
    text = footer(text, source_identity)
    text, entities = presentation(text)
    from telegram_checklist import enabled, prepare, keyboard, bind
    checklist_key = prepare(Store(), token, text, entities) if enabled() else None
    payload = {'chat_id': chat_id, 'text': text, 'entities': entities,
               'disable_notification': silent}
    if checklist_key:
        payload['reply_markup'] = keyboard(checklist_key)
    data = json.dumps(payload).encode()
    req = urllib.request.Request(f'https://api.telegram.org/bot{token}/sendMessage', data=data,
                                 headers={'Content-Type': 'application/json'})
    try:
        with urllib.request.urlopen(req, timeout=15) as response:
            result = json.load(response)
        if not result.get('ok'):
            raise RuntimeError('Telegram rejected message')
        if checklist_key:
            bind(Store(), checklist_key, result['result'])
        return result.get('result', {}).get('message_id')
    except urllib.error.HTTPError as exc:
        if exc.code in (400, 403):
            try:
                reason = json.load(exc).get('description', '').lower()
            except Exception:
                reason = ''
            if any(term in reason for term in ('chat not found', 'bot was kicked', 'bot was blocked', 'not enough rights', 'bot is not a member', 'group chat was deleted')):
                raise TelegramDestinationError('Telegram destination unavailable') from None
        # Do not log exception URLs: Telegram URLs contain the bot token.
        raise RuntimeError(f'Telegram HTTP {exc.code}') from None
    except (urllib.error.URLError, TimeoutError) as exc:
        raise RuntimeError(telegram_connection_error(exc)) from None


def delivery_worker(store, token, chat_id, dry_run, stop):
    from local_settings import delivery_dry_run
    from telegram_routing import deliver_routed
    from scanner_control import initialize as control_initialize
    with store.connect() as db:control_initialize(db)
    while not stop.is_set():
        current_dry_run = delivery_dry_run(store, dry_run)
        with store.connect() as db:
            note=db.execute("""WITH picked AS (SELECT id FROM notification_queue n
                WHERE status='pending' AND next_attempt<=extract(epoch from clock_timestamp())
                AND NOT EXISTS(SELECT 1 FROM migration_holds h WHERE h.queue='notification_queue' AND h.key=n.id)
                ORDER BY id FOR UPDATE SKIP LOCKED LIMIT 1)
                UPDATE notification_queue n SET next_attempt=extract(epoch from clock_timestamp())+90
                FROM picked p WHERE n.id=p.id RETURNING n.id,n.text,n.attempts""").fetchone()
        if note:
            key,text,attempts=note
            try:
                # Strategy alerts share RSI's sound policy, even overnight.
                is_signal = key.startswith(('pin-bars:', 'bb-pin-bars:', 'rsi-pb:'))
                outcome = 'dry-run' if current_dry_run else deliver_routed(store, token, chat_id, text, 'notification:' + key, send_telegram, silent=not is_signal and quiet_hours(), notification_key=key)
                with store.connect() as db:db.execute('UPDATE notification_queue SET status=%s WHERE id=%s',(outcome,key))
                store.log('Queued notification delivered',outcome)
            except Exception as exc:
                from telegram_delivery import DeliveryPending
                store.log('Queued notification delayed', str(exc) if isinstance(exc, DeliveryPending) else 'Delivery failed')
                with store.connect() as db:db.execute('UPDATE notification_queue SET attempts=%s,next_attempt=%s WHERE id=%s',(attempts+1,time.time()+min(300,2**min(attempts+1,9)),key))
            continue
        with store.connect() as db:
            row = db.execute("""WITH picked AS (SELECT id FROM signals s
                WHERE status='pending' AND next_attempt<=extract(epoch from clock_timestamp())
                AND NOT EXISTS(SELECT 1 FROM migration_holds h WHERE h.queue='signals' AND h.key=s.id)
                ORDER BY received FOR UPDATE SKIP LOCKED LIMIT 1)
                UPDATE signals s SET next_attempt=extract(epoch from clock_timestamp())+90
                FROM picked p WHERE s.id=p.id RETURNING s.id,s.payload,s.attempts""").fetchone()
        if not row:
            stop.wait(1)
            continue
        key, raw, attempts = row
        payload = json.loads(raw)
        if payload.get('review_slot') or payload.get('signal_status') != 'provisional':
            # Retire legacy clock reviews and confirmation alerts, including retries.
            # Keep their findings and completed delivery history intact.
            with store.connect() as db:
                db.execute("UPDATE signals SET status='cancelled',error=NULL WHERE id=%s", (key,))
            continue
        store.log('Delivery attempt', f'{key} · attempt {attempts + 1}')
        try:
            if current_dry_run:
                outcome = 'dry-run'
            elif signal_alert_delivered(store, payload):
                outcome = 'suppressed'
            else:
                outcome = deliver_routed(store, token, chat_id, message(payload), signal_alert_event(payload), send_telegram, payload=payload)
            with store.connect() as db:
                db.execute('UPDATE signals SET status=%s,attempts=%s,error=NULL WHERE id=%s',
                           (outcome, attempts + 1, key))
            store.log('Delivery completed', outcome)
        except Exception as exc:
            # Persist a sanitized classification only, never arbitrary exception text.
            error = str(exc) if isinstance(exc, RuntimeError) else 'Delivery failed'
            store.log('Delivery failed', error)
            with store.connect() as db:
                db.execute('UPDATE signals SET attempts=%s,next_attempt=%s,error=%s WHERE id=%s',
                           (attempts + 1, time.time() + min(300, 2 ** min(attempts + 1, 9)), error, key))
        stop.wait(0.1)


def handler_factory(store, rules, secret, dry_run, dashboard=False):
    from local_settings import delivery_dry_run
    class Handler(BaseHTTPRequestHandler):
        def log_message(self, *args):
            pass

        def respond(self, status, body, content_type='application/json'):
            raw = body.encode() if isinstance(body, str) else json.dumps(body).encode()
            self.send_response(status)
            self.send_header('Content-Type', content_type)
            self.send_header('Content-Length', str(len(raw)))
            self.send_header('Cache-Control', 'no-store')
            self.send_header('X-Content-Type-Options', 'nosniff')
            self.end_headers()
            self.wfile.write(raw)

        def do_GET(self):
            if not dashboard:
                self.respond(404, {'error': 'Not found'})
                return
            # Never expose the dashboard/rules/health through the public tunnel.
            if self.headers.get('Host') not in ('localhost:8080', '127.0.0.1:8080', f'localhost:{self.server.server_port}', f'127.0.0.1:{self.server.server_port}'):
                self.respond(404, {'error': 'Not found'})
                return
            from urllib.parse import urlsplit
            route = urlsplit(self.path).path
            if route in ('/', '/signals', '/logs', '/backtest', '/assets', '/candle', '/dashboard'):
                self.respond(200, (ROOT / 'web/index.html').read_text(encoding='utf-8'), 'text/html; charset=utf-8')
                return
            if route == '/web/config.js' and not test_database():
                from dashboard_server import browser_config
                self.respond(200,'window.DASHBOARD_CONFIG = '+json.dumps(browser_config(ROOT))+';','text/javascript')
                return
            if route.startswith('/api/') and not test_database():
                self.respond(403,{'error':'Use authenticated Supabase APIs'})
                return
            if route.startswith('/web/'):
                if route == '/web/version.json':
                    from version_info import local_versions
                    self.respond(200, local_versions())
                    return
                allowed_files = {'style.css':'text/css', 'app.js':'text/javascript', 'config.js':'text/javascript', 'chart.js':'text/javascript', 'vendor/lightweight-charts.js':'text/javascript', 'favicon.svg':'image/svg+xml'}
                name = route.removeprefix('/web/')
                if name in allowed_files:
                    self.respond(200, (ROOT / 'web' / name).read_text(encoding='utf-8'), allowed_files[name])
                else:
                    self.respond(404, {'error':'Not found'})
                return
            if route == '/api/local-settings':
                from local_settings import read
                self.respond(200, read(store))
                return
            if route in ('/api/telegram-routing', '/api/assets', '/api/findings', '/api/momentum', '/api/pin-bars', '/api/bb-pin-bars', '/api/rsi-pb', '/api/csv-backtests', '/api/candles', '/api/followup', '/api/logs', '/api/backtests','/api/catchup','/api/updates','/api/versions'):
                from dashboard_api import read
                try:
                    self.respond(200, read(store, self.path))
                except LookupError as exc:
                    self.respond(404, {'error':str(exc)})
                except (ValueError, TypeError):
                    self.respond(400, {'error':'Invalid dashboard request'})
                except (DatabaseError, PoolTimeout, WorkerOwned):
                    self.respond(503, {'error':'Postgres unavailable; processing is paused'})
                return
            if self.path == '/health':
                self.respond(200, {'ok': True, 'dry_run': delivery_dry_run(store, dry_run), 'rules': rules})
            elif self.path == '/api/feedback/export':
                from finding_feedback import export
                self.respond(200, export(store))
