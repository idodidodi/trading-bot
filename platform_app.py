        def do_POST(self):
            if dashboard and not test_database():
                self.respond(403,{'error':'Use authenticated Supabase APIs'})
                return
            if dashboard and self.path in ('/api/feedback', '/api/assets', '/api/backtests', '/api/finding-state','/api/catchup','/api/updates','/api/csv-backtests','/api/connection-test','/api/local-settings'):
                from finding_feedback import save
                host = self.headers.get('Host')
                allowed = (f'localhost:{self.server.server_port}', f'127.0.0.1:{self.server.server_port}')
                if (host not in allowed or self.headers.get('Origin') not in ('http://' + host,)
                        or self.headers.get('Content-Type') != 'application/json'):
                    self.respond(403, {'error': 'Feedback must be saved from the local dashboard'})
                    return
                try:
                    size = int(self.headers.get('Content-Length', '0'))
                    if not 0 < size <= (2_100_000 if self.path=='/api/csv-backtests' else 32768):
                        raise ValueError('Invalid body size')
                    self.connection.settimeout(2)
                    body = json.loads(self.rfile.read(size))
                    if not isinstance(body, dict):
                        raise ValueError('Expected JSON object')
                    if self.path=='/api/local-settings':
                        from local_settings import save as save_settings
                        try:
                            self.respond(200, save_settings(store, body))
                        except ValueError as exc:
                            self.respond(400, {'error': str(exc)})
                    elif self.path=='/api/connection-test':
                        from connection_tests import run, ConnectionTestError
                        try:
                            self.respond(200,run(body.get('action'),rules,store))
                        except ConnectionTestError as exc:
                            self.respond(502,{'error':str(exc)})
                    elif self.path=='/api/csv-backtests':
                        from csv_backtests import save as save_csv
                        self.respond(200,save_csv(store,body))
                    elif self.path=='/api/catchup':
                        from scanner_control import request
                        if body.get('action')!='request':raise ValueError('Invalid scanner action')
                        self.respond(202,request(store))
                    elif self.path=='/api/updates':
                        import windows_update
                        self.respond(202,windows_update.request_check())
                    elif self.path == '/api/finding-state':
                        from finding_state import change
                        self.respond(200, change(store, ROOT, body))
                    elif self.path == '/api/backtests':
                        from backtest_jobs import start
                        self.respond(202, start(store, body))
                    elif self.path == '/api/assets':
                        from dashboard_api import ensure
                        from managed_assets import change
                        ensure(store)
                        self.respond(200, change(store, body))
                    else:
                        self.respond(200, save(store, ROOT, body))
                except LookupError as exc:
                    self.respond(409, {'error': str(exc)})
                except (ValueError, TypeError, OSError) as exc:
                    self.respond(400, {'error': str(exc) if self.path=='/api/csv-backtests' and isinstance(exc,ValueError) else 'Invalid asset configuration or feedback'})
                except (DatabaseError, PoolTimeout, WorkerOwned):
                    self.respond(503, {'error': 'Postgres unavailable. Reload before retrying a save.'})
                return
            if dashboard or self.path != '/webhook':
                self.respond(404, {'error': 'Not found'})
                return
            try:
                size = int(self.headers.get('Content-Length', '0'))
                if not 0 < size <= 16_384:
                    raise ValueError('Invalid body size')
                self.connection.settimeout(2)
                body = json.loads(self.rfile.read(size))
                if not isinstance(body, dict):
                    raise ValueError('Expected JSON object')
                supplied = body.get('secret')
                if not isinstance(supplied, str) or not hmac.compare_digest(supplied.encode(), secret.encode()):
                    self.respond(401, {'error': 'Unauthorized'})
                    return
                payload = validate_signal(body, rules)
                created = store.insert(payload)
                self.respond(202, {'accepted': True, 'duplicate': not created})
            except (ValueError, TypeError, KeyError, OSError):
                self.respond(400, {'error': 'Invalid signal, JSON, or rules version'})
